import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const version = "0.144.6";
const protocolRoot = resolve(root, "protocol", "codex-app-server", version);
const notificationPath = resolve(protocolRoot, "typescript", "ServerNotification.ts");
const requestPath = resolve(protocolRoot, "typescript", "ServerRequest.ts");
const schemaPath = resolve(protocolRoot, "codex_app_server_protocol.v2.schemas.json");
const outputPath = resolve(root, "crates", "mcg-codex-app-server", "src", "protocol_generated.rs");

const notifications = readFileSync(notificationPath, "utf8");
const requests = readFileSync(requestPath, "utf8");
const schema = readFileSync(schemaPath);
const methods = (source) => [...source.matchAll(/"method":\s*"([^"]+)"/g)].map((match) => match[1]);
const rustArray = (values) => values.map((value) => `    ${JSON.stringify(value)},`).join("\n");
const fingerprint = createHash("sha256").update(schema).digest("hex");

const generated = `//! GENERATED CODE. DO NOT EDIT BY HAND.
//!
//! Generated by scripts/generate-codex-app-server-rust.mjs from the exact
//! Codex ${version} app-server schema and ts-rs unions.

use serde::{Deserialize, Serialize};
use serde_json::Value;

pub const GENERATED_CODEX_VERSION: &str = ${JSON.stringify(version)};
pub const GENERATED_PROTOCOL_VERSION: &str = "v2";
pub const GENERATED_SCHEMA_SHA256: &str = ${JSON.stringify(fingerprint)};

pub const SERVER_NOTIFICATION_METHODS: &[&str] = &[
${rustArray(methods(notifications))}
];

pub const SERVER_REQUEST_METHODS: &[&str] = &[
${rustArray(methods(requests))}
];

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(untagged)]
pub enum RequestId {
    Integer(i64),
    String(String),
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ServerNotification {
    pub method: String,
    #[serde(default)]
    pub params: Value,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ServerRequest {
    pub id: RequestId,
    pub method: String,
    #[serde(default)]
    pub params: Value,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ServerResponse {
    pub id: RequestId,
    #[serde(default)]
    pub result: Option<Value>,
    #[serde(default)]
    pub error: Option<Value>,
}

#[must_use]
pub fn is_known_notification(method: &str) -> bool {
    SERVER_NOTIFICATION_METHODS.contains(&method)
}

#[must_use]
pub fn is_known_server_request(method: &str) -> bool {
    SERVER_REQUEST_METHODS.contains(&method)
}
`;

writeFileSync(outputPath, generated);
console.log(`generated ${outputPath}\nCodex ${version}\nschema sha256 ${fingerprint}`);
